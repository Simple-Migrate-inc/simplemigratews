// Compiles the dashboard stylesheet with its own Tailwind config, outside the
// Next.js CSS pipeline, and wraps it so the public-site PurgeCSS pass keeps it
// intact. Usage: node scripts/dashboard/build-css.mjs [--watch]
import { spawnSync, spawn } from "child_process";
import { readFileSync, writeFileSync, watch } from "fs";

const OUT = "src/app/styles/dashboard.generated.css";
const args = ["tailwindcss", "-c", "tailwind.dashboard.config.js", "-i", "src/app/styles/dashboard.src.css", "-o", OUT, "--minify"];

function wrap() {
    const css = readFileSync(OUT, "utf8");
    if (css.startsWith("/*! purgecss start ignore */")) return;
    writeFileSync(OUT, `/*! purgecss start ignore */\n/* GENERATED by scripts/dashboard/build-css.mjs — do not edit. */\n${css}\n/*! purgecss end ignore */\n`);
}

if (process.argv.includes("--watch")) {
    spawn("npx", [...args, "--watch"], { stdio: "inherit" });
    let t;
    watch(OUT, () => {
        clearTimeout(t);
        t = setTimeout(wrap, 50);
    });
} else {
    const r = spawnSync("npx", args, { stdio: "inherit" });
    if (r.status !== 0) process.exit(r.status ?? 1);
    wrap();
}
